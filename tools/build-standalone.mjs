/*
 * Build `index.html`: the whole engine in one file, no imports, no origin.
 *
 * Several ways of opening this project cannot fetch `src/*.js`. `file://`
 * refuses module imports outright, and a preview pane that injects markup into a
 * sandboxed origin -- a WebView, an iframe with a srcdoc, which is what Paseo
 * does with a linked HTML file -- has no base URL to resolve a module against.
 * Both paint the control panel around a black canvas and never start the
 * simulation, which reads as a broken toy rather than a blocked request. An
 * inline script needs no origin at all.
 *
 * So the page at the root of this repo -- the one to open -- is generated here,
 * from `src/page.template.html` and a bundle of `src/*.js`. There is one entry point and
 * it works everywhere, rather than a page that works over a server plus a second
 * page that works anywhere.
 *
 *   node tools/build-standalone.mjs
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATE = 'src/page.template.html';
const OUTPUT = 'index.html';
// Read from the project root, not src/: that is the specifier the emitted page
// would need if it could load a module at all, which is the tag this replaces.
const SCRIPT_TAG = '<script type="module" src="src/main.js"></script>';
const STYLES_TAG = '<link rel="stylesheet" href="styles.css">';

const SOURCE_NOTE = `<!--
  THIS IS NOT A PAGE. It is the markup that tools/build-standalone.mjs compiles
  into \`index.html\` at the root of this repo -- which is the file to open.

  Opened on its own this looks broken rather than unfinished: its stylesheet and
  module are relative paths that resolve to nothing from here, so it paints
  unstyled controls around a dead canvas and logs no error at all. A preview pane
  that follows a link to any *.html makes that mistake silently, which is why the
  name carries "template" and why a visible notice is emitted below.
-->`;
const STANDALONE_NOTE = `<!--
  Generated from src/page.template.html + src/*.js by tools/build-standalone.mjs. One
  file, nothing fetched: it opens from disk, from a sandboxed preview pane, or
  from any static server. To change it, edit src/ and re-run that build.
-->`;

const banner =
  'Generated by tools/build-standalone.mjs from src/page.template.html + src/*.js + styles.css.\n' +
  'Edit those and re-run the build; nothing here is hand-written.';

/*
 * Bundle src/main.js to a single classic script.
 *
 * Driven through the esbuild CLI rather than its JS API because nixpkgs ships
 * esbuild as a binary with no accompanying library, and this project has no
 * node_modules and no network to install one. `--format=iife` rather than a
 * module: the whole point is to survive contexts where a module script cannot
 * fetch anything. `--footer` is not used because the wrapper only needs the
 * output to be a self-executing expression, which iife already is.
 */
function findEsbuild() {
  const candidates = [
    process.env.ESBUILD,
    'esbuild',
    ...globEsbuildStorePaths(),
  ].filter(Boolean);
  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ['--version'], { encoding: 'utf8', env: esbuildEnv() });
    // esbuild touches a temporary directory, so a sandboxed spawn can report
    // both a usable result and an EPERM error. Trust the exit status and the
    // version string, which is what actually proves the binary runs here.
    if (probe.status === 0 && /^\d+\.\d+/u.test(probe.stdout ?? '')) return candidate;
  }
  throw new Error(
    'esbuild not found; set ESBUILD to an esbuild binary '
    + '(on NixOS: nix-build -E \'with import <nixpkgs> {}; esbuild\' -o .gc-roots/esbuild)',
  );
}

/**
 * esbuild writes through a temporary directory. Point it inside the workspace so
 * the build works in sandboxes that deny writes elsewhere (and does not litter).
 */
function esbuildEnv() {
  const tmp = path.join(root, '.tmp');
  return { ...process.env, TMPDIR: tmp };
}

/** nix store paths are content-addressed, so search by name rather than pin one. */
function globEsbuildStorePaths() {
  try {
    return readdirSync('/nix/store')
      .filter((entry) => /^[a-z0-9]{32}-esbuild-[0-9]/.test(entry))
      .map((entry) => path.join('/nix/store', entry, 'bin', 'esbuild'))
      .filter((candidate) => existsSync(candidate));
  } catch {
    return [];
  }
}

function bundle() {
  const esbuild = findEsbuild();
  const result = spawnSync(
    esbuild,
    [
      'src/main.js',
      '--bundle',
      '--format=iife',
      '--target=es2020',
      '--minify',
      '--legal-comments=none',
      '--log-level=warning',
    ],
    { cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024, env: esbuildEnv() },
  );
  if (result.status !== 0) {
    throw new Error(`esbuild failed: ${result.stderr || result.stdout}`);
  }
  const js = result.stdout;
  // An inline script ends at the first `</script` it sees, wherever that is.
  return js.replaceAll('</script', '<\\/script');
}

export function renderStandalone() {
  const page = readFileSync(path.join(root, TEMPLATE), 'utf8');
  for (const marker of [SCRIPT_TAG, STYLES_TAG, SOURCE_NOTE]) {
    if (!page.includes(marker)) {
      throw new Error(`${TEMPLATE} no longer contains ${marker.slice(0, 48)}..., which this build replaces`);
    }
  }
  const css = readFileSync(path.join(root, 'styles.css'), 'utf8');
  return page
    .replace('<!doctype html>', `<!doctype html>\n<!-- ${banner} -->`)
    .replace(SOURCE_NOTE, STANDALONE_NOTE)
    .replace(STYLES_TAG, `<style>\n${css}\n</style>`)
    .replace(SCRIPT_TAG, `<script>${bundle()}</script>`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(path.join(root, '.tmp'), { recursive: true });
  const html = renderStandalone();
  writeFileSync(path.join(root, OUTPUT), html);
  console.log(`${OUTPUT}: ${(html.length / 1024).toFixed(1)} KB`);
}
